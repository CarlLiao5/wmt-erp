CREATE TABLE sem_performance_daily (
  id varchar(64) NOT NULL,
  tenant_id varchar(36) NOT NULL,
  store_id varchar(36) NOT NULL,
  report_date date NOT NULL,
  campaign_id varchar(191) NOT NULL,
  campaign_name varchar(255),
  sku varchar(191) NOT NULL,
  item_id varchar(191),
  impressions int,
  clicks int,
  ctr decimal(19,8),
  ad_spend decimal(19,4),
  cpc decimal(19,4),
  sales decimal(19,4),
  roas decimal(19,8),
  currency varchar(3) DEFAULT 'USD',
  source_id varchar(191) NOT NULL,
  payload json,
  received_at datetime(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY sem_performance_daily_unique (store_id, report_date, campaign_id, sku, source_id),
  KEY sem_performance_daily_scope_idx (tenant_id, store_id, report_date, sku)
);
