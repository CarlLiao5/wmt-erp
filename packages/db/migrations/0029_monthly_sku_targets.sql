CREATE TABLE `target_batches` (
  `id` varchar(36) NOT NULL,
  `tenant_id` varchar(36) NOT NULL,
  `month` varchar(7) NOT NULL,
  `revision` int NOT NULL DEFAULT 1,
  `status` varchar(20) NOT NULL,
  `formula_version` varchar(40) NOT NULL,
  `source_snapshot_at` datetime(3) DEFAULT NULL,
  `created_by` varchar(36) NOT NULL,
  `created_at` datetime(3) NOT NULL,
  `updated_at` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `target_batches_tenant_month_revision_unique` (`tenant_id`, `month`, `revision`),
  KEY `target_batches_scope_idx` (`tenant_id`, `month`, `status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE `sku_target_rows` (
  `id` varchar(36) NOT NULL,
  `batch_id` varchar(36) NOT NULL,
  `tenant_id` varchar(36) NOT NULL,
  `month` varchar(7) NOT NULL,
  `store_id` varchar(36) NOT NULL,
  `sku` varchar(191) NOT NULL,
  `item_id` varchar(191) DEFAULT NULL,
  `product_name` varchar(512) DEFAULT NULL,
  `owner_name` varchar(191) DEFAULT NULL,
  `inventory_quantity` decimal(19,4) DEFAULT NULL,
  `last_month_units` decimal(19,4) DEFAULT NULL,
  `last_month_days` int DEFAULT NULL,
  `last_month_avg_daily_sales` decimal(19,6) DEFAULT NULL,
  `last_month_avg_price` decimal(19,4) DEFAULT NULL,
  `expected_daily_sales` decimal(19,6) DEFAULT NULL,
  `selling_days` decimal(19,6) DEFAULT NULL,
  `quantity_target` decimal(19,6) DEFAULT NULL,
  `amount_target` decimal(19,4) DEFAULT NULL,
  `missing_reasons` json DEFAULT NULL,
  `status` varchar(20) NOT NULL,
  `created_at` datetime(3) NOT NULL,
  `updated_at` datetime(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `sku_target_rows_batch_store_sku_unique` (`batch_id`, `store_id`, `sku`),
  KEY `sku_target_rows_scope_idx` (`tenant_id`, `month`, `store_id`, `sku`),
  KEY `sku_target_rows_batch_idx` (`batch_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
