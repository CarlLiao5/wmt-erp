CREATE TABLE IF NOT EXISTS `lingxing_shipment_sku_costs` (
  `id` varchar(64) NOT NULL COMMENT '稳定的明细主键',
  `tenant_id` varchar(36) NOT NULL COMMENT 'ERP 租户 ID',
  `shipment_number` varchar(191) NOT NULL COMMENT '头程表中的 WFS 货件号，对应领星 cargoCode',
  `shipping_list_code` varchar(191) NOT NULL COMMENT '领星发货单号',
  `shipping_status` varchar(32) NOT NULL COMMENT '领星发货单状态',
  `source_row_ids` json NOT NULL COMMENT '关联的头程源记录 ID',
  `contract_numbers` json NOT NULL COMMENT '头程合同编号原值列表',
  `po_numbers` json NOT NULL COMMENT '从合同编号中解析的 PO 列表，不进行任意成本分摊',
  `purchase_batch_numbers` json NOT NULL COMMENT '关联采购批次号列表',
  `source_store_names` json NOT NULL COMMENT '头程记录中的来源店铺名列表',
  `lingxing_store_name` varchar(191) DEFAULT NULL COMMENT '领星发货单店铺名',
  `msku` varchar(191) DEFAULT NULL COMMENT '领星 MSKU',
  `sku` varchar(191) DEFAULT NULL COMMENT '领星 SKU',
  `product_name` varchar(512) DEFAULT NULL COMMENT '领星商品名称',
  `shipped_quantity` decimal(19,4) DEFAULT NULL COMMENT '领星已发货数量',
  `purchase_unit_cost` decimal(19,4) DEFAULT NULL COMMENT '领星采购单价',
  `line_purchase_cost` decimal(19,4) DEFAULT NULL COMMENT '已发货数量乘以采购单价',
  `currency` varchar(8) DEFAULT NULL COMMENT '采购单价币种',
  `raw_payload` json NOT NULL COMMENT '领星发货单及对应货件 SKU 原始数据',
  `batch_id` varchar(64) NOT NULL COMMENT '同步批次 ID',
  `idempotency_key` varchar(64) NOT NULL COMMENT '货件、发货单及 SKU 的稳定幂等键',
  `first_seen_at` datetime(3) NOT NULL COMMENT '首次写入时间（UTC）',
  `synced_at` datetime(3) NOT NULL COMMENT '最近同步时间（UTC）',
  `created_at` datetime(3) NOT NULL COMMENT '创建时间（UTC）',
  `updated_at` datetime(3) NOT NULL COMMENT '更新时间（UTC）',
  PRIMARY KEY (`id`),
  UNIQUE KEY `lingxing_shipment_sku_costs_idempotency_unique` (`tenant_id`, `idempotency_key`),
  KEY `lingxing_shipment_sku_costs_cargo_idx` (`tenant_id`, `shipment_number`),
  KEY `lingxing_shipment_sku_costs_sku_idx` (`tenant_id`, `sku`),
  KEY `lingxing_shipment_sku_costs_batch_idx` (`tenant_id`, `batch_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='领星已发货货件的 SKU 数量、采购单价、行金额及头程合同 PO 映射';
