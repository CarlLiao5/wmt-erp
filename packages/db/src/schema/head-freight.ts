import { datetime, index, json, mysqlTable, unique, varchar } from 'drizzle-orm/mysql-core';

export const wecomBotConfigs = mysqlTable('wecom_bot_configs', {
  tenantId: varchar('tenant_id', { length: 36 }).primaryKey(),
  encryptedBotKey: varchar('encrypted_bot_key', { length: 1024 }),
  encryptedBotId: varchar('encrypted_bot_id', { length: 1024 }),
  encryptedBotSecret: varchar('encrypted_bot_secret', { length: 1024 }),
  documentUrl: varchar('document_url', { length: 1024 }).notNull(),
  tableId: varchar('table_id', { length: 191 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }).notNull(),
});

export const headFreightRows = mysqlTable('head_freight_rows', {
  id: varchar('id', { length: 64 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }),
  sourceStoreName: varchar('source_store_name', { length: 191 }),
  contractNumber: varchar('contract_number', { length: 191 }),
  purchaseBatchNumber: varchar('purchase_batch_number', { length: 191 }),
  sku: varchar('sku', { length: 191 }),
  productName: varchar('product_name', { length: 512 }),
  quantity: varchar('quantity', { length: 64 }),
  cartonCount: varchar('carton_count', { length: 64 }),
  wfsShipmentNumber: varchar('wfs_shipment_number', { length: 191 }),
  freightForwarderInboundNumber: varchar('freight_forwarder_inbound_number', { length: 191 }),
  trackingNumber: varchar('tracking_number', { length: 191 }),
  shippedAt: varchar('shipped_at', { length: 64 }),
  etd: varchar('etd', { length: 64 }),
  eta: varchar('eta', { length: 64 }),
  currentStatus: varchar('current_status', { length: 128 }),
  signedStatus: varchar('signed_status', { length: 128 }),
  billableWeight: varchar('billable_weight', { length: 64 }),
  totalFreight: varchar('total_freight', { length: 64 }),
  logisticsProvider: varchar('logistics_provider', { length: 191 }),
  warehouse: varchar('warehouse', { length: 191 }),
  paymentStatus: varchar('payment_status', { length: 128 }),
  shippingStatus: varchar('shipping_status', { length: 128 }),
  shippingMethod: varchar('shipping_method', { length: 128 }),
  channel: varchar('channel', { length: 128 }),
  matchStatus: varchar('match_status', { length: 32 }).notNull().default('unmatched'),
  sourceRowId: varchar('source_row_id', { length: 191 }).notNull(),
  idempotencyKey: varchar('idempotency_key', { length: 191 }).notNull(),
  batchId: varchar('batch_id', { length: 64 }).notNull(),
  rawPayloadId: varchar('raw_payload_id', { length: 191 }),
  payload: json('payload'),
  receivedAt: datetime('received_at', { mode: 'date', fsp: 3 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }).notNull(),
}, (table) => [
  unique('head_freight_idempotency_unique').on(table.tenantId, table.idempotencyKey),
  index('head_freight_scope_idx').on(table.tenantId, table.storeId, table.updatedAt),
  index('head_freight_source_idx').on(table.tenantId, table.sourceRowId),
]);
