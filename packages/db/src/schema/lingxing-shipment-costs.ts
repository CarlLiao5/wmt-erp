import { datetime, decimal, index, json, mysqlTable, unique, varchar } from 'drizzle-orm/mysql-core';

export const lingxingShipmentSkuCosts = mysqlTable('lingxing_shipment_sku_costs', {
  id: varchar('id', { length: 64 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  shipmentNumber: varchar('shipment_number', { length: 191 }).notNull(),
  shippingListCode: varchar('shipping_list_code', { length: 191 }).notNull(),
  shippingStatus: varchar('shipping_status', { length: 32 }).notNull(),
  sourceRowIds: json('source_row_ids').notNull(),
  contractNumbers: json('contract_numbers').notNull(),
  poNumbers: json('po_numbers').notNull(),
  purchaseBatchNumbers: json('purchase_batch_numbers').notNull(),
  sourceStoreNames: json('source_store_names').notNull(),
  lingxingStoreName: varchar('lingxing_store_name', { length: 191 }),
  msku: varchar('msku', { length: 191 }),
  sku: varchar('sku', { length: 191 }),
  productName: varchar('product_name', { length: 512 }),
  shippedQuantity: decimal('shipped_quantity', { precision: 19, scale: 4 }),
  purchaseUnitCost: decimal('purchase_unit_cost', { precision: 19, scale: 4 }),
  linePurchaseCost: decimal('line_purchase_cost', { precision: 19, scale: 4 }),
  currency: varchar('currency', { length: 8 }),
  rawPayload: json('raw_payload').notNull(),
  batchId: varchar('batch_id', { length: 64 }).notNull(),
  idempotencyKey: varchar('idempotency_key', { length: 64 }).notNull(),
  firstSeenAt: datetime('first_seen_at', { mode: 'date', fsp: 3 }).notNull(),
  syncedAt: datetime('synced_at', { mode: 'date', fsp: 3 }).notNull(),
  createdAt: datetime('created_at', { mode: 'date', fsp: 3 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }).notNull(),
}, (table) => [
  unique('lingxing_shipment_sku_costs_idempotency_unique').on(table.tenantId, table.idempotencyKey),
  index('lingxing_shipment_sku_costs_cargo_idx').on(table.tenantId, table.shipmentNumber),
  index('lingxing_shipment_sku_costs_sku_idx').on(table.tenantId, table.sku),
  index('lingxing_shipment_sku_costs_batch_idx').on(table.tenantId, table.batchId),
]);
