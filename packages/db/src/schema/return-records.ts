import { datetime, decimal, index, int, mysqlTable, tinyint, varchar } from 'drizzle-orm/mysql-core';

export const returnRecords = mysqlTable('return_records', {
  id: varchar('id', { length: 191 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }).notNull(),
  returnOrderId: varchar('return_order_id', { length: 64 }),
  orderId: varchar('order_id', { length: 191 }).notNull(),
  orderNumber: varchar('order_number', { length: 191 }),
  customerOrderId: varchar('customer_order_id', { length: 64 }),
  returnOrderItemId: varchar('return_order_item_id', { length: 64 }),
  itemId: varchar('item_id', { length: 191 }),
  sku: varchar('sku', { length: 191 }),
  productName: varchar('product_name', { length: 512 }),
  quantity: int('quantity'),
  status: varchar('status', { length: 80 }).notNull(),
  amount: decimal('amount', { precision: 19, scale: 4 }),
  currency: varchar('currency', { length: 8 }),
  reason: varchar('reason', { length: 512 }),
  reasonCode: varchar('reason_code', { length: 64 }),
  returnedAt: varchar('returned_at', { length: 40 }),
  returnInitiatedAt: datetime('return_initiated_at', { mode: 'date', fsp: 3 }),
  refundIssuedAt: datetime('refund_issued_at', { mode: 'date', fsp: 3 }),
  isWfs: tinyint('is_wfs'),
  storeName: varchar('store_name', { length: 128 }),
  returnMethod: varchar('return_method', { length: 64 }),
  deliveryStatus: varchar('delivery_status', { length: 64 }),
  channelName: varchar('channel_name', { length: 64 }),
  refundStatus: varchar('refund_status', { length: 64 }),
  refundCoveredBy: varchar('refund_covered_by', { length: 64 }),
  refundChannelCoveredBy: varchar('refund_channel_covered_by', { length: 64 }),
  isReturnForException: tinyint('is_return_for_exception'),
  returnChannelName: varchar('return_channel_name', { length: 128 }),
  createdAt: datetime('created_at', { mode: 'date', fsp: 3 }),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }),
}, (table) => [
  index('return_records_scope_date_idx').on(table.tenantId, table.storeId, table.returnedAt),
  index('return_records_tenant_date_idx').on(table.tenantId, table.returnedAt),
  index('return_records_order_idx').on(table.tenantId, table.orderId),
  index('return_records_sku_idx').on(table.tenantId, table.storeId, table.sku),
]);
