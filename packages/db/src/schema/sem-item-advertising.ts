import { date, datetime, decimal, index, int, json, mysqlTable, unique, varchar } from 'drizzle-orm/mysql-core';

export const semItemAdvertisingFacts = mysqlTable('sem_item_advertising_facts', {
  id: varchar('id', { length: 64 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }).notNull(),
  campaignId: varchar('campaign_id', { length: 191 }).notNull(),
  sku: varchar('sku', { length: 191 }).notNull(),
  itemId: varchar('item_id', { length: 191 }),
  factDate: date('fact_date').notNull(),
  periodStart: date('period_start'),
  periodEnd: date('period_end'),
  spend: decimal('spend', { precision: 19, scale: 4 }),
  attributedSales: decimal('attributed_sales', { precision: 19, scale: 4 }),
  impressions: int('impressions'),
  clicks: int('clicks'),
  attributedUnits: int('attributed_units'),
  currency: varchar('currency', { length: 3 }).default('USD'),
  complete: int('complete').notNull().default(0),
  sourceId: varchar('source_id', { length: 191 }).notNull(),
  payload: json('payload'),
  receivedAt: datetime('received_at', { mode: 'date', fsp: 3 }).notNull(),
}, (t) => [
  unique('sem_item_advertising_fact_unique').on(t.storeId, t.campaignId, t.sku, t.factDate, t.sourceId),
  index('sem_item_advertising_scope_idx').on(t.tenantId, t.storeId, t.factDate, t.sku),
]);

export const semPerformanceDaily = mysqlTable('sem_performance_daily', {
  id: varchar('id', { length: 64 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }).notNull(),
  reportDate: date('report_date').notNull(),
  campaignId: varchar('campaign_id', { length: 191 }).notNull(),
  campaignName: varchar('campaign_name', { length: 255 }),
  sku: varchar('sku', { length: 191 }).notNull(),
  itemId: varchar('item_id', { length: 191 }),
  impressions: int('impressions'),
  clicks: int('clicks'),
  ctr: decimal('ctr', { precision: 19, scale: 8 }),
  adSpend: decimal('ad_spend', { precision: 19, scale: 4 }),
  cpc: decimal('cpc', { precision: 19, scale: 4 }),
  sales: decimal('sales', { precision: 19, scale: 4 }),
  roas: decimal('roas', { precision: 19, scale: 8 }),
  currency: varchar('currency', { length: 3 }).default('USD'),
  sourceId: varchar('source_id', { length: 191 }).notNull(),
  payload: json('payload'),
  receivedAt: datetime('received_at', { mode: 'date', fsp: 3 }).notNull(),
}, (t) => [
  unique('sem_performance_daily_unique').on(t.storeId, t.reportDate, t.campaignId, t.sku, t.sourceId),
  index('sem_performance_daily_scope_idx').on(t.tenantId, t.storeId, t.reportDate, t.sku),
]);
