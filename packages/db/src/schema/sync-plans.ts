import { datetime, index, int, json, mysqlTable, unique, varchar } from 'drizzle-orm/mysql-core';

export const syncPlans = mysqlTable('sync_plans', {
  id: varchar('id', { length: 36 }).primaryKey(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }).notNull(),
  resource: varchar('resource', { length: 80 }).notNull(),
  mode: varchar('mode', { length: 16 }).notNull(),
  requestedFrom: datetime('requested_from', { mode: 'date', fsp: 3 }),
  requestedTo: datetime('requested_to', { mode: 'date', fsp: 3 }),
  status: varchar('status', { length: 32 }).notNull().default('planned'),
  intervalMinutes: int('interval_minutes').notNull().default(0),
  overlapDays: int('overlap_days').notNull().default(0),
  nextRunAt: datetime('next_run_at', { mode: 'date', fsp: 3 }),
  enabled: int('enabled').notNull().default(0),
  boundaryReason: varchar('boundary_reason', { length: 255 }),
  coverageFrom: datetime('coverage_from', { mode: 'date', fsp: 3 }),
  coverageTo: datetime('coverage_to', { mode: 'date', fsp: 3 }),
  source: varchar('source', { length: 32 }).notNull().default('walmart_api'),
  resultPayload: json('result_payload'),
  lastError: varchar('last_error', { length: 1024 }),
  createdAt: datetime('created_at', { mode: 'date', fsp: 3 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }).notNull(),
}, (table) => [
  unique('sync_plan_scope_unique').on(table.tenantId, table.storeId, table.resource, table.mode),
  index('sync_plan_status_idx').on(table.tenantId, table.storeId, table.status),
  index('sync_plan_schedule_idx').on(table.enabled, table.mode, table.nextRunAt),
]);

export const syncWindows = mysqlTable('sync_windows', {
  id: varchar('id', { length: 36 }).primaryKey(),
  planId: varchar('plan_id', { length: 36 }).notNull(),
  tenantId: varchar('tenant_id', { length: 36 }).notNull(),
  storeId: varchar('store_id', { length: 36 }).notNull(),
  resource: varchar('resource', { length: 80 }).notNull(),
  batchId: varchar('batch_id', { length: 64 }).notNull(),
  windowFrom: datetime('window_from', { mode: 'date', fsp: 3 }).notNull(),
  windowTo: datetime('window_to', { mode: 'date', fsp: 3 }).notNull(),
  status: varchar('status', { length: 32 }).notNull().default('planned'),
  requestParams: json('request_params'),
  cursor: varchar('cursor', { length: 191 }),
  pageCount: int('page_count').notNull().default(0),
  recordCount: int('record_count').notNull().default(0),
  attempts: int('attempts').notNull().default(0),
  coverageFrom: datetime('coverage_from', { mode: 'date', fsp: 3 }),
  coverageTo: datetime('coverage_to', { mode: 'date', fsp: 3 }),
  source: varchar('source', { length: 32 }).notNull().default('walmart_api'),
  boundaryReason: varchar('boundary_reason', { length: 255 }),
  lastError: varchar('last_error', { length: 1024 }),
  createdAt: datetime('created_at', { mode: 'date', fsp: 3 }).notNull(),
  updatedAt: datetime('updated_at', { mode: 'date', fsp: 3 }).notNull(),
}, (table) => [
  unique('sync_window_scope_unique').on(table.tenantId, table.storeId, table.resource, table.windowFrom, table.windowTo, table.batchId),
  index('sync_window_plan_idx').on(table.planId, table.status),
  index('sync_window_scope_idx').on(table.tenantId, table.storeId, table.resource, table.windowFrom),
]);
